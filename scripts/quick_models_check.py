"""Check that vLLM (Transformers backend) reproduces a custom model's own greedy output.

For a few prompts, compares the first tokens generated by vLLM against the model's reference
implementation in transformers (trust_remote_code). Exploratory sanity check before speed tests.

Usage (WSL, venv-vllm, GPU free): python scripts/quick_models_check.py MODEL_NAME [--tokens 32]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import httpx

sys.path.insert(0, str(Path(__file__).parent))
import quick_models as q


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("--tokens", type=int, default=32)
    a = ap.parse_args()
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer

    repo = q.MODELS[a.name][0]
    path = q.local(repo)
    trust = repo in q.EXTRA_ARGS
    tok = AutoTokenizer.from_pretrained(path, trust_remote_code=trust)
    prompts = q.pick(q.bench(), 4)
    cases = [
        (lang, q.encode_prompt(tok, prompts[lang][1]["messages"])) for lang in ("en", "hi", "ta")
    ]
    p = q.serve(path, None, q.OUT / f"server-{a.name}-check.log")
    try:
        vl = []
        for _, ids in cases:
            r = httpx.post(
                f"http://127.0.0.1:{q.PORT}/v1/completions",
                json={"model": "m", "prompt": ids, "max_tokens": a.tokens, "temperature": 0},
                timeout=300,
            ).json()
            vl.append(tok.encode(r["choices"][0]["text"], add_special_tokens=False))
    finally:
        q.stop(p)
    model = AutoModelForCausalLM.from_pretrained(
        path, dtype=torch.bfloat16, trust_remote_code=trust
    )
    model = model.to("cuda").eval()
    ok = 0
    for (lang, ids), v in zip(cases, vl, strict=True):
        with torch.inference_mode():
            out = model.generate(
                torch.tensor([ids], device="cuda"),
                max_new_tokens=a.tokens,
                do_sample=False,
                use_cache=True,
            )
        hf = out[0, len(ids) :].tolist()
        n = min(len(hf), len(v))
        same = next((i for i in range(n) if hf[i] != v[i]), n)
        ok += same >= min(16, n)
        print(f"{lang}: first {same}/{n} tokens identical")
        print(f"   vLLM: {tok.decode(v[:24])!r}")
        print(f"   HF  : {tok.decode(hf[:24])!r}")
    print("VERDICT:", "MATCH" if ok == len(cases) else "MISMATCH (do not trust vLLM speed numbers)")


if __name__ == "__main__":
    main()
